const G: Record<string, string> = Object.fromEntries(Object.entries(ROWS).map(([k, v]) => [k, v.replaceAll(' ', '')]));

export const ADV = 6;
export const glyph = (ch: string) => G[ch] ?? G[ch.toUpperCase()] ?? G[' '];
export const hasGlyph = (ch: string) => ch in G || ch.toUpperCase() in G;
export const textW = (s: string, scale = 1) => (s.length * ADV - 1) * scale;

export function text(s: string, x: number, y: number, col: string, scale = 1, shadow?: string) {
  const draw = (ox: number, oy: number, c: string) => {
    for (let k = 0; k < s.length; k++) {
      const gph = glyph(s[k]);
      for (let b = 0; b < 35; b++)
        if (gph[b] === '#') rect(Math.round(x) + ox + (k * ADV + (b % 5)) * scale, Math.round(y) + oy + Math.floor(b / 5) * scale, scale, scale, c);
    }
  };
  if (shadow) draw(scale, scale, shadow);
  draw(0, 0, col);
}

/** Centered text helper. */
export const textC = (s: string, cx: number, y: number, col: string, scale = 1, shadow?: string) =>
  text(s, Math.round(cx - textW(s, scale) / 2), y, col, scale, shadow);
